"""Compare the production seed filter with a bounded bilinear seed hypothesis.

The trial changes only the inlier mask fed to the existing model pipeline.
Known scene points are used only to measure the real native renderer maps.
Run against the fixtures generated by synthetic_vergence.py.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import time
from unittest.mock import patch

import cv2
import numpy as np
from PIL import Image

from synthetic_vergence import BASELINE_M, CASES, WIDTH, HEIGHT, FOCAL, alignment, measured_render, stats
from stereofine.alignment_refinement import (
    corrected_point_residuals, patch_correlations, point_quality, refine_alignment,
)
from stereofine.lens_refinement import refine_residual_field


def bilinear_seed(left, right, shape, photo_good):
    """Fit vertical displacement with a single additional x*y term."""
    h, w = shape
    x, y = ((.5 * (left + right) - [(w - 1) / 2, (h - 1) / 2]) / [w, h]).T
    design = np.column_stack([np.ones(len(x)), x, y, x * y])
    dy = right[:, 1] - left[:, 1]
    indices = np.flatnonzero(photo_good)
    if len(indices) < 40:
        return None
    # Count at most one observation per 4px left and right cell during seed
    # estimation. Repeated orientations of a feature must not vote repeatedly.
    for points in (left, right):
        _, unique = np.unique(np.floor(points[indices] / 4), axis=0, return_index=True)
        indices = indices[np.sort(unique)]
    if len(indices) < 40:
        return None
    matrix, target = design[indices], dy[indices]
    rng = np.random.default_rng(1337)
    samples = rng.integers(len(indices), size=(2200, 4))
    sample_design = matrix[samples]
    usable = np.abs(np.linalg.det(sample_design)) > .002
    coefficients = np.linalg.solve(sample_design[usable], target[samples[usable], None])[:, :, 0]
    # Bound the corner-to-center contribution to 2.5% of image height.
    coefficients = coefficients[np.abs(coefficients[:, 3]) <= .10 * h]
    if not len(coefficients):
        return None
    best_count = 0
    beta = None
    for block in np.array_split(coefficients, (len(coefficients) + 63) // 64):
        errors = np.abs(target[:, None] - matrix @ block.T)
        counts = np.count_nonzero(errors <= 3., axis=0)
        index = int(np.argmax(counts))
        if counts[index] > best_count:
            beta, best_count = block[index], int(counts[index])
    if best_count < 40:
        return None
    for _ in range(2):
        inliers = np.abs(target - matrix @ beta) <= 3.
        if inliers.sum() < 40:
            return None
        beta, _, rank, _ = np.linalg.lstsq(matrix[inliers], target[inliers], rcond=None)
        if rank < 4 or abs(beta[3]) > .10 * h:
            return None
    return np.abs(dy - design @ beta) <= 3., float(beta[3])


def screen_trial(baseline, trial, left, right, shape, scale, info):
    """Conservative pilot decision using only image measurements."""
    if info['recovered'] < max(30, .25 * info['old_seed']) or info['removed'] > .05 * info['old_seed']:
        return dict(accepted=False, reason='no_consistent_expansion_of_seed')
    if not (trial['correction'].get('trapez_apply') or {}).get('enabled'):
        return dict(accepted=False, reason='projective_stage_did_not_pass_existing_guards')
    before, zones_before = point_quality(left, corrected_point_residuals(
        baseline['correction'], left, right, shape, scale), shape, scale)
    after, zones_after = point_quality(left, corrected_point_residuals(
        trial['correction'], left, right, shape, scale), shape, scale)
    if before['p95_abs'] is None or before['p95_abs'] * scale <= 3.:
        return dict(accepted=False, reason='baseline_does_not_need_recovery')
    decision = alignment._assess_spatial_holdout(before, after, zones_before, zones_after, scale)
    return dict(**decision, before=before, after=after)


def run_pair(left, right, method, *, reserve_blocks=False, screen=False, screen_fold=None):
    fit = alignment._analyze_matched_points
    captured = []

    def collect(lp, rp, shape, scale, method, *, inlier_mask=None):
        if not captured:
            captured.append((lp, rp, shape, scale, inlier_mask))
        return fit(lp, rp, shape, scale, method, inlier_mask=inlier_mask)

    start = time.perf_counter()
    with patch.object(alignment, '_analyze_matched_points', collect):
        baseline = alignment.analyze_pair_features(left, right, method, WIDTH)
    baseline_time = time.perf_counter() - start
    lp, rp, shape, scale, old_mask = captured[0]
    start = time.perf_counter()
    lg, rg, _ = alignment.resize_pair_for_analysis(left, right, WIDTH)
    if reserve_blocks or screen:
        from compare_rectification import training_mask, withheld
        train = training_mask(lp, rp)
        reserved = withheld(lp)
        checks = lp[reserved], rp[reserved]
        if screen_fold is not None:
            from select_subpixel_candidate import confirmation_split
            use_for_screen = confirmation_split(checks[0]) == screen_fold
            checks = tuple(points[use_for_screen] for points in checks)
        lp, rp = lp[train], rp[train]
        old_mask = alignment._fit_vertical_ransac_filter(.5 * (lp + rp), rp, lp, shape)['mask']
        if reserve_blocks:
            baseline = fit(lp, rp, shape, scale, method, inlier_mask=old_mask)
            baseline = refine_alignment(baseline, lp, rp, old_mask, lg, rg, scale, method)
            baseline = refine_residual_field(baseline, lp, rp, lg, rg, scale)
    photo_good = patch_correlations(lg, rg, lp, rp) >= .85
    seed = bilinear_seed(lp, rp, shape, photo_good)
    if seed is None:
        return {'baseline': baseline}, dict(baseline_seconds=baseline_time, trial='insufficient_seed_support')
    mask, xy = seed
    # The new hypothesis may retain an already accepted feature. Newly
    # admitted matches must additionally pass the unchanged patch check.
    mask &= old_mask | photo_good
    try:
        trial = fit(lp, rp, shape, scale, method, inlier_mask=mask)
        trial = refine_alignment(trial, lp, rp, mask, lg, rg, scale, method)
        trial = refine_residual_field(trial, lp, rp, lg, rg, scale)
    except (RuntimeError, np.linalg.LinAlgError) as exc:
        return {'baseline': baseline}, dict(baseline_seconds=baseline_time, trial=str(exc))
    info = dict(
        baseline_seconds=baseline_time, additional_seconds=time.perf_counter() - start,
        old_seed=int(old_mask.sum()), new_seed=int(mask.sum()), recovered=int((mask & ~old_mask).sum()),
        removed=int((old_mask & ~mask).sum()), xy_analysis_px=xy)
    if screen:
        cl, cr = checks
        valid = patch_correlations(lg, rg, cl, cr) >= .90
        indices = np.flatnonzero(valid)
        for points in (cl, cr):
            _, unique = np.unique(np.floor(points[indices] / 4), axis=0, return_index=True)
            indices = indices[np.sort(unique)]
        info['screen'] = screen_trial(baseline, trial, cl[indices], cr[indices], shape, scale, info)
    return {'baseline': baseline, 'bilinear': trial}, info


def evaluate(left, right, methods, controls, *, screen=False):
    lp, rp, world = (controls[key] for key in ('left', 'right', 'world'))
    anchor = .5 * (lp + rp)
    edge = ((anchor[:, 0] < .15 * WIDTH) | (anchor[:, 0] > .85 * WIDTH)
            | (anchor[:, 1] < .15 * HEIGHT) | (anchor[:, 1] > .85 * HEIGHT))
    zones = np.clip((anchor / [WIDTH, HEIGHT] * 3).astype(int), 0, 2)
    zone_id = zones[:, 0] + 3 * zones[:, 1]
    # Only relative disparity matters. Remove the common horizontal offset.
    reference_disparity = FOCAL * BASELINE_M / world[:, 2]
    for method in methods:
        fits, info = run_pair(left, right, method, screen=screen)
        measured = {}
        for label, fit in fits.items():
            pair, p, q, valid = measured_render(left, right, fit['correction'], lp, rp)
            measured[label] = (p, q, valid, pair[0].shape[:2])
            del pair
        common = np.logical_and.reduce([row[2] for row in measured.values()])
        rows = {}
        for label, (p, q, valid, shape) in measured.items():
            dy = q[:, 1] - p[:, 1]
            depth_error = (p[:, 0] - q[:, 0] - reference_disparity)[common]
            rows[label] = dict(model=fits[label]['model'], all=stats(dy[common]),
                outer_15_percent=stats(dy[common & edge]),
                zones=[stats(dy[common & (zone_id == i)]) for i in range(9)],
                centered_disparity_error=stats(depth_error - np.median(depth_error)),
                retained_controls=int(valid.sum()), output_area_fraction=float(np.prod(shape) / (WIDTH * HEIGHT)))
        yield dict(method=method, common_controls=int(common.sum()), fit=info, variants=rows)


def evaluate_real(left, right, methods):
    from compare_rectification import withheld
    from select_neural_candidate import control_points

    lg, rg, _ = alignment.resize_pair_for_analysis(left, right, WIDTH)
    lp, rp, _ = control_points(lg, rg)
    reserved = withheld(lp)
    scale_xy = np.array(left.shape[:2][::-1]) / np.array(lg.shape[::-1])
    lp, rp = ((points[reserved] + .5) * scale_xy - .5 for points in (lp, rp))
    for method in methods:
        fits, info = run_pair(left, right, method, reserve_blocks=True)
        measured = {}
        for label, fit in fits.items():
            pair, p, q, valid = measured_render(left, right, fit['correction'], lp, rp)
            measured[label] = (q[:, 1] - p[:, 1], valid, pair[0].shape[:2])
            del pair
        common = np.logical_and.reduce([row[1] for row in measured.values()])
        rows = {label: dict(model=fits[label]['model'], all=stats(dy[common]),
                            retained_controls=int(valid.sum()),
                            output_area_fraction=float(np.prod(shape) / np.prod(left.shape[:2])))
                for label, (dy, valid, shape) in measured.items()}
        yield dict(method=method, common_controls=int(common.sum()), fit=info, variants=rows)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('fixture_dir', type=Path)
    parser.add_argument('--cases', nargs='+', choices=[case['name'] for case in CASES])
    parser.add_argument('--methods', nargs='+', choices=['AKAZE', 'SIFT'], default=['AKAZE', 'SIFT'])
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--real-sbs', type=Path, help='Compare one real SBS with spatially held-out LK checks')
    parser.add_argument('--screen', action='store_true',
                        help='Fit the trial on reserved-block training data and evaluate a guarded switch')
    args = parser.parse_args()
    cv2.setNumThreads(4)
    records = []
    if args.real_sbs:
        pixels = np.asarray(Image.open(args.real_sbs).convert('RGB'))
        left, right = (np.ascontiguousarray(eye) for eye in np.split(pixels, 2, axis=1))
        records.extend(evaluate_real(left, right, args.methods))
        args.output.write_text(json.dumps(records, indent=2, allow_nan=False), encoding='utf-8')
        print(json.dumps(records, indent=2))
        return
    for name in args.cases or [case['name'] for case in CASES]:
        pixels = np.asarray(Image.open(args.fixture_dir / 'inputs' / f'{name}_sbs.png').convert('RGB'))
        left, right = (np.ascontiguousarray(eye) for eye in np.split(pixels, 2, axis=1))
        del pixels
        with np.load(args.fixture_dir / 'results' / f'{name}_AKAZE_controls.npz') as controls:
            for row in evaluate(left, right, args.methods, controls, screen=args.screen):
                records.append(dict(case=name, **row))
                print(name, row['method'], row['fit'], {
                    k: (v['model'], v['all']['p95']) for k, v in row['variants'].items()}, flush=True)
                args.output.write_text(json.dumps(records, indent=2, allow_nan=False), encoding='utf-8')


if __name__ == '__main__':
    main()
