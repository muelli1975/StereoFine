def _holdout_summary_is_better(baseline: dict | None, corrected: dict | None) -> bool:
    """Threshold-free Pareto gate for adding geometric complexity.

    The candidate must strictly improve holdout mean absolute vertical error and
    may not worsen median, p90, p95 or maximum error.  This rejects tiny fits
    that merely trade one part of the image against another, without inventing a
    new pixel threshold.
    """
    if not baseline or not corrected:
        return False
    metrics = ("mean_abs", "median_abs", "p90_abs", "p95_abs", "max_abs")
    try:
        base = {key: float(baseline[key]) for key in metrics}
        cand = {key: float(corrected[key]) for key in metrics}
    except (KeyError, TypeError, ValueError):
        return False
    if not np.isfinite(list(base.values()) + list(cand.values())).all():
        return False
    return bool(
        cand["mean_abs"] < base["mean_abs"]
        and all(cand[key] <= base[key] for key in ("median_abs", "p90_abs", "p95_abs", "max_abs"))
    )


def _holdout_model_is_better(candidate: dict | None) -> bool:
    """Conservative auto-enable gate for a fitted residual model."""
    if not candidate or not bool(candidate.get("ready", False)):
        return False
    if candidate.get("eval_mode") != "spatial_holdout":
        return False
    return _holdout_summary_is_better(
        candidate.get("baseline_holdout") or {},
        candidate.get("vertical_holdout") or {},
    )


def analyze_pair_features(
    left: np.ndarray,
    right: np.ndarray,
    method: str,
    max_width: int,
) -> dict:
    """Vergence model basis: keep affine output, compare V/H candidates.

    This basis deliberately does not promote a new correction model.  The
    actual applied correction remains the stable unweighted Affine-LMS result.
    The sidecar stores the measured residual fields for:
      - Affine only
      - Affine + V only (vertical residual slope over x)
      - Affine + H only (current horizontal vergence term; vertical residual is
        expected to stay unchanged in this point model)
      - Affine + V+H

    The purpose is to evaluate the current Vergence model over multiple data
    sets without adding UI controls or changing the stable basis.
    """
    try:
        import cv2
    except Exception as exc:
        raise RuntimeError("OpenCV ist nicht installiert oder konnte nicht geladen werden.") from exc

    left_gray, right_gray, analysis_scale = resize_pair_for_analysis(left, right, max_width)
    h, w = left_gray.shape[:2]

    method_upper = method.upper()
    if method_upper == "AKAZE":
        detector = cv2.AKAZE_create()
        norm_type = cv2.NORM_HAMMING
    elif method_upper == "SIFT":
        if not hasattr(cv2, "SIFT_create"):
            raise RuntimeError("SIFT ist in dieser OpenCV-Version nicht verfügbar.")
        detector = cv2.SIFT_create()
        norm_type = cv2.NORM_L2
    else:
        raise RuntimeError(f"Unbekanntes Analyseverfahren: {method}")

    kp_left, desc_left = detector.detectAndCompute(left_gray, None)
    kp_right, desc_right = detector.detectAndCompute(right_gray, None)

    if desc_left is None or desc_right is None or len(kp_left) < 4 or len(kp_right) < 4:
        raise RuntimeError("Zu wenige Merkmale für eine zuverlässige Analyse gefunden.")

    matcher = cv2.BFMatcher(norm_type, crossCheck=False)
    raw_matches = matcher.knnMatch(desc_right, desc_left, k=2)

    good_matches = []
    for pair in raw_matches:
        if len(pair) != 2:
            continue
        m, n = pair
        if m.distance < 0.75 * n.distance:
            good_matches.append(m)

    if len(good_matches) < 8:
        raise RuntimeError("Zu wenige stabile Übereinstimmungen nach dem Matching gefunden.")

    pts_right = np.float32([kp_right[m.queryIdx].pt for m in good_matches]).reshape(-1, 1, 2)
    pts_left = np.float32([kp_left[m.trainIdx].pt for m in good_matches]).reshape(-1, 1, 2)

    # y-RANSAC is the stereoscopic first-stage filter: it scores only vertical
    # plausibility and deliberately ignores horizontal disparity, because
    # horizontal disparity is scene depth, not an alignment error.
    raw_right_points_all = pts_right.reshape(-1, 2).astype(np.float64)
    raw_left_points_all = pts_left.reshape(-1, 2).astype(np.float64)
    raw_anchor_points_all = 0.5 * (raw_right_points_all + raw_left_points_all)

    y_filter_result = _fit_vertical_ransac_filter(
        raw_anchor_points_all,
        raw_right_points_all,
        raw_left_points_all,
        left_gray.shape,
        threshold_analysis_px=3.0,
    )
    mask = np.asarray(y_filter_result.get("mask", []), dtype=bool).reshape(-1)
    if len(mask) != len(raw_right_points_all):
        raise RuntimeError("y-RANSAC konnte keine stabile Inlier-Gruppe bestimmen.")
    if int(mask.sum()) < 8:
        raise RuntimeError("Zu wenige Inlier für eine stabile Analyse gefunden (y-RANSAC).")

    right_in = raw_right_points_all[mask]
    left_in = raw_left_points_all[mask]

    scale, rotation_deg, centre_shift_y_analysis, affine_fit_method = _lms_affine_from_vertical_residuals(
        right_in,
        left_in,
        left_gray.shape,
    )
    vertical_shift_px = centre_shift_y_analysis / analysis_scale

    # Predict residual after our actual symmetric affine correction, not after
    # any discarded 2D reprojection matrix.
    half_scale = max(1e-6, scale) ** 0.5
    left_mid = _transform_points_by_center_params(
        left_in,
        left_gray.shape,
        -rotation_deg / 2.0,
        1.0 / half_scale,
        0.0,
        -centre_shift_y_analysis / 2.0,
    )
    right_mid = _transform_points_by_center_params(
        right_in,
        right_gray.shape,
        rotation_deg / 2.0,
        half_scale,
        0.0,
        centre_shift_y_analysis / 2.0,
    )

    pre_affine_vertical_signed = right_in[:, 1] - left_in[:, 1]
    pre_affine_anchor_points = 0.5 * (right_in + left_in)

    affine_vertical_signed = right_mid[:, 1] - left_mid[:, 1]
    affine_vertical_abs = np.abs(affine_vertical_signed) / analysis_scale
    horizontal_signed = right_mid[:, 0] - left_mid[:, 0]
    horizontal_abs = np.abs(horizontal_signed) / analysis_scale

    coverage_percent = _point_coverage_percent(left_in, left_gray.shape)
    # Pipeline v4: keine Quadrantenbedingung mehr.  Die alte einfache V/H-
    # Diagnose bleibt nur als Messwert erhalten; die eigentliche Trapez-/
    # Vergence-Stufe wird weiter unten über Gesamt-Inlier, Trainingspunkte,
    # Design-Matrix-Stabilität und harte numerische Plausibilität beurteilt.
    vergence_candidate_ready = int(mask.sum()) >= TRAPEZ_MIN_TOTAL_INLIERS

    vergence_v_analysis, vergence_h_analysis = _fit_vergence_from_affine_residuals(
        left_mid,
        right_mid,
        left_gray.shape,
    )
    vergence_v_candidate_px = vergence_v_analysis / analysis_scale
    vergence_h_candidate_px = vergence_h_analysis / analysis_scale

    cx = (w - 1.0) / 2.0
    cy = (h - 1.0) / 2.0
    x_norm = (left_mid[:, 0] - cx) / max(1.0, float(w))
    y_norm = (left_mid[:, 1] - cy) / max(1.0, float(h))

    # Current application semantics:
    #   V changes y by a term over x and therefore changes vertical residuals.
    #   H changes x by a term over y and therefore does not change the measured
    #   vertical point residual in this simplified point-field simulation.
    v_only_vertical_signed = affine_vertical_signed - vergence_v_analysis * x_norm
    h_only_vertical_signed = affine_vertical_signed.copy()
    vh_vertical_signed = v_only_vertical_signed.copy()

    # H is still stored as a diagnostic of the y-dependent horizontal disparity
    # trend.  Depth itself remains horizontal disparity, so this is not used as
    # a quality score for stereo alignment; it is just a model sanity check.
    horizontal_centered = horizontal_signed - float(np.median(horizontal_signed))
    h_corrected_horizontal_signed = horizontal_centered - vergence_h_analysis * y_norm

    def residual_summary(signed_values_analysis: np.ndarray) -> dict:
        signed_px = np.asarray(signed_values_analysis, dtype=np.float64).reshape(-1) / max(1e-12, analysis_scale)
        if len(signed_px) == 0:
            return {
                "mean_signed": None,
                "mean_abs": None,
                "median_abs": None,
                "p90_abs": None,
                "p95_abs": None,
                "max_abs": None,
            }
        abs_px = np.abs(signed_px)
        return {
            "mean_signed": float(np.mean(signed_px)),
            "mean_abs": float(np.mean(abs_px)),
            "median_abs": float(np.median(abs_px)),
            "p90_abs": float(np.percentile(abs_px, 90)),
            "p95_abs": float(np.percentile(abs_px, 95)),
            "max_abs": float(np.max(abs_px)),
        }

    pre_affine_zone3x3 = _vertical_residual_zone_stats(
        pre_affine_anchor_points,
        pre_affine_vertical_signed,
        left_gray.shape,
        analysis_scale,
        ZONE_DIAGNOSTICS_GRID,
    )
    affine_zone3x3 = _vertical_residual_zone_stats(
        left_mid,
        affine_vertical_signed,
        left_gray.shape,
        analysis_scale,
        ZONE_DIAGNOSTICS_GRID,
    )
    v_only_zone3x3 = _vertical_residual_zone_stats(
        left_mid,
        v_only_vertical_signed,
        left_gray.shape,
        analysis_scale,
        ZONE_DIAGNOSTICS_GRID,
    )
    h_only_zone3x3 = _vertical_residual_zone_stats(
        left_mid,
        h_only_vertical_signed,
        left_gray.shape,
        analysis_scale,
        ZONE_DIAGNOSTICS_GRID,
    )
    vh_zone3x3 = _vertical_residual_zone_stats(
        left_mid,
        vh_vertical_signed,
        left_gray.shape,
        analysis_scale,
        ZONE_DIAGNOSTICS_GRID,
    )

    y_residual_candidates = {}
    for y_model_name, y_model_terms in Y_RESIDUAL_MODEL_SPECS.items():
        candidate = _fit_y_residual_candidate(
            y_model_name,
            y_model_terms,
            left_mid,
            right_mid,
            affine_vertical_signed,
            left_gray.shape,
            analysis_scale,
        )
        candidate["vs_affine"] = _zone_improvement_stats(affine_zone3x3, candidate["zone3x3"])
        base_holdout = candidate.get("baseline_holdout") or {}
        cand_holdout = candidate.get("vertical_holdout") or {}
        if base_holdout.get("mean_abs") is not None and cand_holdout.get("mean_abs") is not None:
            candidate["vs_affine_holdout_mean_abs_delta"] = float(cand_holdout["mean_abs"] - base_holdout["mean_abs"])
        y_residual_candidates[y_model_name] = candidate

    candidate_summaries = {
        "affine": {
            "vertical": residual_summary(affine_vertical_signed),
            "horizontal_centered": residual_summary(horizontal_centered),
        },
        "v_only": {
            "vertical": residual_summary(v_only_vertical_signed),
            "params": {"vergence_v_px": float(vergence_v_candidate_px), "vergence_h_px": 0.0},
        },
        "h_only": {
            "vertical": residual_summary(h_only_vertical_signed),
            "horizontal_centered_after_h": residual_summary(h_corrected_horizontal_signed),
            "params": {"vergence_v_px": 0.0, "vergence_h_px": float(vergence_h_candidate_px)},
            "note": "H term shifts x over y; vertical point residual is unchanged by design.",
        },
        "v_plus_h": {
            "vertical": residual_summary(vh_vertical_signed),
            "horizontal_centered_after_h": residual_summary(h_corrected_horizontal_signed),
            "params": {"vergence_v_px": float(vergence_v_candidate_px), "vergence_h_px": float(vergence_h_candidate_px)},
        },
    }
    for y_model_name, y_candidate in y_residual_candidates.items():
        candidate_summaries[y_model_name] = {
            "vertical": y_candidate.get("vertical"),
            "vertical_holdout": y_candidate.get("vertical_holdout"),
            "baseline_holdout": y_candidate.get("baseline_holdout"),
            "vs_affine_holdout_mean_abs_delta": y_candidate.get("vs_affine_holdout_mean_abs_delta"),
            "ready": y_candidate.get("ready"),
            "terms": y_candidate.get("terms"),
            "model_summary": y_candidate.get("model_summary"),
            "note": "Low-order y-residual model after Affine-LMS; y_quad is visually applied when ready in this apply basis.",
        }

