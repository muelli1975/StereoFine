def _largest_all_valid_rectangle(valid: np.ndarray) -> tuple[int, int, int, int] | None:
    """Return the largest axis-aligned rectangle fully inside a valid mask.

    The mask is generated by warping an all-white source mask with the same
    affine transform as the right image. Therefore every True pixel represents
    real source image content after the warp.
    
    Coordinates are x0, y0, x1, y1 with x1/y1 exclusive.
    """
    if valid.ndim != 2 or not valid.any():
        return None

    h, w = valid.shape
    heights = [0] * w
    best_area = 0
    best_rect = None

    for y in range(h):
        row = valid[y]
        for x in range(w):
            heights[x] = heights[x] + 1 if row[x] else 0

        stack = []
        for x in range(w + 1):
            current_height = heights[x] if x < w else 0

            while stack and heights[stack[-1]] > current_height:
                height = heights[stack.pop()]
                x0 = stack[-1] + 1 if stack else 0
                x1 = x
                width = x1 - x0
                area = height * width

                if area > best_area:
                    best_area = area
                    y1 = y + 1
                    y0 = y1 - height
                    best_rect = (x0, y0, x1, y1)

            stack.append(x)

    if best_rect is None:
        return None

    x0, y0, x1, y1 = best_rect

    # Deterministic safety margin against interpolation fringes at the exact
    # border of the warped image. This is not a crop heuristic; it is a fixed
    # one-pixel guard band around a mathematically valid rectangle.
    margin = 2
    if x1 - x0 > margin * 2 and y1 - y0 > margin * 2:
        x0 += margin
        y0 += margin
        x1 -= margin
        y1 -= margin

    if x1 - x0 <= 2 or y1 - y0 <= 2:
        return None

    return x0, y0, x1, y1

def resize_array_for_preview(arr: np.ndarray, scale: float) -> np.ndarray:
    if scale >= 0.999:
        return arr

    height, width = arr.shape[:2]
    new_width = max(1, round(width * scale))
    new_height = max(1, round(height * scale))

    img = Image.fromarray(arr, "RGB")
    img = img.resize((new_width, new_height), Image.Resampling.LANCZOS)
    return np.asarray(img, dtype=np.uint8)

def resize_pair_for_preview(
    left: np.ndarray,
    right: np.ndarray,
    max_width: int,
    max_height: int,
) -> tuple[np.ndarray, np.ndarray, float]:
    """Create a fast working copy for live preview rendering.

    The returned scale maps original half-image pixels to preview pixels.
    Full-resolution export can later use the same offsets on the originals.
    """
    lh, lw = left.shape[:2]
    rh, rw = right.shape[:2]

    common_w = max(1, min(lw, rw))
    common_h = max(1, min(lh, rh))

    scale = min(
        max_width / common_w,
        max_height / common_h,
        PREVIEW_MAX_WIDTH / common_w,
        1.0,
    )

    return (
        resize_array_for_preview(left, scale),
        resize_array_for_preview(right, scale),
        scale,
    )

def resize_pair_for_analysis(
    left: np.ndarray,
    right: np.ndarray,
    max_width: int,
) -> tuple[np.ndarray, np.ndarray, float]:
    """Create grayscale analysis images limited by half-image width."""
    lh, lw = left.shape[:2]
    rh, rw = right.shape[:2]

    common_w = max(1, min(lw, rw))
    scale = min(max_width / common_w, 1.0)

    left_small = resize_array_for_preview(left, scale)
    right_small = resize_array_for_preview(right, scale)

    left_gray = np.asarray(Image.fromarray(left_small, "RGB").convert("L"), dtype=np.uint8)
    right_gray = np.asarray(Image.fromarray(right_small, "RGB").convert("L"), dtype=np.uint8)

    return left_gray, right_gray, scale

def _transform_points(matrix: np.ndarray, points: np.ndarray) -> np.ndarray:
    pts = points.reshape(-1, 2).astype(np.float64)
    matrix = np.asarray(matrix, dtype=np.float64)

    if matrix.shape == (3, 3):
        ones = np.ones((pts.shape[0], 1), dtype=np.float64)
        hom = np.hstack([pts, ones]) @ matrix.T
        denom = hom[:, 2:3]
        denom[np.abs(denom) < 1e-12] = 1e-12
        return hom[:, :2] / denom

    ones = np.ones((pts.shape[0], 1), dtype=np.float64)
    hom = np.hstack([pts, ones])
    return hom @ matrix.reshape(2, 3).T

def _point_coverage_percent(points: np.ndarray, image_shape: tuple[int, int]) -> float:
    pts = points.reshape(-1, 2)
    if len(pts) < 3:
        return 0.0

    h, w = image_shape[:2]
    x0, y0 = np.min(pts, axis=0)
    x1, y1 = np.max(pts, axis=0)
    area = max(0.0, float(x1 - x0)) * max(0.0, float(y1 - y0))
    image_area = max(1.0, float(w * h))
    return float(np.clip(area / image_area * 100.0, 0.0, 100.0))

def _grid_zone_indices(points: np.ndarray, image_shape: tuple[int, int], grid: int = 3) -> np.ndarray:
    pts = np.asarray(points, dtype=np.float64).reshape(-1, 2)
    h, w = image_shape[:2]
    if len(pts) == 0 or h <= 0 or w <= 0:
        return np.zeros((len(pts),), dtype=np.int32)
    x = np.clip(pts[:, 0], 0.0, max(0.0, float(w) - 1.0))
    y = np.clip(pts[:, 1], 0.0, max(0.0, float(h) - 1.0))
    col = np.clip((x / max(1.0, float(w)) * grid).astype(np.int32), 0, grid - 1)
    row = np.clip((y / max(1.0, float(h)) * grid).astype(np.int32), 0, grid - 1)
    return row * grid + col

def _grid_zone_counts(points: np.ndarray, image_shape: tuple[int, int], grid: int = 3) -> list[int]:
    zones = _grid_zone_indices(points, image_shape, grid)
    return [int(np.sum(zones == idx)) for idx in range(grid * grid)]

def _zone_balanced_weights(points: np.ndarray, image_shape: tuple[int, int], grid: int = 3) -> np.ndarray:
    """Give each occupied 3x3 zone the same total influence.

    Dense zones therefore do not dominate the least-squares solve just because
    they contain many more feature matches. The final weights are normalized to
    a mean value of 1.0 so ordinary and weighted LMS stay numerically similar.
    """
    pts = np.asarray(points, dtype=np.float64).reshape(-1, 2)
    n = len(pts)
    if n == 0:
        return np.zeros((0,), dtype=np.float64)
    zones = _grid_zone_indices(pts, image_shape, grid)
    weights = np.zeros((n,), dtype=np.float64)
    for idx in range(grid * grid):
        mask = zones == idx
        count = int(np.sum(mask))
        if count > 0:
            weights[mask] = 1.0 / float(count)
    total = float(np.sum(weights))
    if total > 1e-12:
        weights *= float(n) / total
    else:
        weights[:] = 1.0
    return weights

def _zone_capped_weights(
    points: np.ndarray,
    image_shape: tuple[int, int],
    grid: int = 3,
    cap_per_zone: int = Y_RESIDUAL_ZONE_SOFT_CAP_PER_ZONE,
) -> np.ndarray:
    """Softly prevent dense zones from dominating a residual-model fit.

    Unlike hard zone balancing, sparse zones are not boosted to the same total
    influence as dense zones.  Dense zones are merely capped: if a zone contains
    more than `cap_per_zone` points, every point in that zone is down-weighted so
    the zone contributes roughly `cap_per_zone` effective points.  This keeps a
    reliable centre from overpowering the fit while avoiding the earlier problem
    where thin edge zones received too much authority.
    """
    pts = np.asarray(points, dtype=np.float64).reshape(-1, 2)
    n = len(pts)
    if n == 0:
        return np.zeros((0,), dtype=np.float64)
    zones = _grid_zone_indices(pts, image_shape, grid)
    weights = np.ones((n,), dtype=np.float64)
    cap = max(1, int(cap_per_zone))
    for idx in range(grid * grid):
        mask = zones == idx
        count = int(np.sum(mask))
        if count > cap:
            weights[mask] = float(cap) / float(count)
    mean = float(np.mean(weights))
    if mean > 1e-12:
        weights /= mean
    return weights

def _safe_corrcoef(a: np.ndarray, b: np.ndarray) -> float | None:
    aa = np.asarray(a, dtype=np.float64).reshape(-1)
    bb = np.asarray(b, dtype=np.float64).reshape(-1)
    n = min(len(aa), len(bb))
    if n < 4:
        return None
    aa = aa[:n]
    bb = bb[:n]
    mask = np.isfinite(aa) & np.isfinite(bb)
    if int(np.sum(mask)) < 4:
        return None
    aa = aa[mask]
    bb = bb[mask]
    if float(np.std(aa)) <= 1e-12 or float(np.std(bb)) <= 1e-12:
        return None
    return float(np.corrcoef(aa, bb)[0, 1])

def _y_residual_design_matrix(
    left_points_after_affine: np.ndarray,
    right_points_after_affine: np.ndarray,
    image_shape: tuple[int, int],
    terms: list[str],
) -> tuple[np.ndarray, list[str]]:
    """Build a low-order y-residual design matrix.

    x/y are normalized image coordinates after Affine-LMS.  `disp` is the
    centered horizontal disparity after Affine-LMS and is included only as a
    diagnostic predictor: it may explain depth-linked vertical residuals, but it
    is not itself a stereo-safe x-error target.
    """
    left_pts = np.asarray(left_points_after_affine, dtype=np.float64).reshape(-1, 2)
    right_pts = np.asarray(right_points_after_affine, dtype=np.float64).reshape(-1, 2)
    n = min(len(left_pts), len(right_pts))
    left_pts = left_pts[:n]
    right_pts = right_pts[:n]
    h, w = image_shape[:2]
    cx = (float(w) - 1.0) / 2.0
    cy = (float(h) - 1.0) / 2.0
    x = (left_pts[:, 0] - cx) / max(1.0, float(w))
    y = (left_pts[:, 1] - cy) / max(1.0, float(h))
    disp = right_pts[:, 0] - left_pts[:, 0]
    disp = disp - float(np.median(disp)) if len(disp) else disp
    disp = disp / max(1.0, float(w))

    columns: list[np.ndarray] = []
    labels: list[str] = []
    for term in terms:
        if term == "constant":
            columns.append(np.ones((n,), dtype=np.float64))
        elif term == "x":
            columns.append(x)
        elif term == "y":
            columns.append(y)
        elif term == "xy":
            columns.append(x * y)
        elif term == "x2":
            columns.append((x * x) - float(np.mean(x * x)) if n else x * x)
        elif term == "y2":
            columns.append((y * y) - float(np.mean(y * y)) if n else y * y)
        elif term == "disp":
            columns.append(disp)
        else:
            raise ValueError(f"Unbekannter y-Restmodell-Term: {term}")
        labels.append(term)
    if not columns:
        return np.zeros((n, 0), dtype=np.float64), []
    return np.column_stack(columns), labels

def _holdout_mask_for_residual_basis(points: np.ndarray, stride: int = Y_RESIDUAL_HOLDOUT_STRIDE) -> np.ndarray:
    pts = np.asarray(points, dtype=np.float64).reshape(-1, 2)
    n = len(pts)
    if n == 0:
        return np.zeros((0,), dtype=bool)
    stride = max(3, int(stride))
    # Sort spatially before taking every nth point.  This makes the holdout more
    # image-distributed than simply using descriptor order.
    order = np.lexsort((pts[:, 0], pts[:, 1]))
    eval_mask = np.zeros((n,), dtype=bool)
    eval_mask[order[::stride]] = True
    if int(np.sum(eval_mask)) < max(8, n // (stride + 1)):
        eval_mask[:] = False
        eval_mask[::stride] = True
    if int(np.sum(eval_mask)) >= n - 4:
        eval_mask[:] = False
        eval_mask[::stride] = True
    return eval_mask

def _residual_model_support_summary(points: np.ndarray, image_shape: tuple[int, int]) -> dict:
    pts = np.asarray(points, dtype=np.float64).reshape(-1, 2)
    counts = _grid_zone_counts(pts, image_shape, ZONE_DIAGNOSTICS_GRID)
    reliable = [c for c in counts if int(c) >= Y_RESIDUAL_MIN_RELIABLE_ZONE_POINTS]
    return {
        "total_points": int(len(pts)),
        "grid": int(ZONE_DIAGNOSTICS_GRID),
        "counts": [int(c) for c in counts],
        "occupied_zones": int(sum(1 for c in counts if int(c) > 0)),
        "reliable_zone_min_points": int(Y_RESIDUAL_MIN_RELIABLE_ZONE_POINTS),
        "reliable_zones": int(len(reliable)),
        "min_required_reliable_zones": int(Y_RESIDUAL_MIN_RELIABLE_ZONES),
        "zone_soft_cap_per_zone": int(Y_RESIDUAL_ZONE_SOFT_CAP_PER_ZONE),
    }

def _fit_y_residual_candidate(
    name: str,
    terms: list[str],
    left_points_after_affine: np.ndarray,
    right_points_after_affine: np.ndarray,
    affine_vertical_signed_analysis: np.ndarray,
    image_shape: tuple[int, int],
    analysis_scale: float,
) -> dict:
    left_pts = np.asarray(left_points_after_affine, dtype=np.float64).reshape(-1, 2)
    right_pts = np.asarray(right_points_after_affine, dtype=np.float64).reshape(-1, 2)
    residual = np.asarray(affine_vertical_signed_analysis, dtype=np.float64).reshape(-1)
    n = min(len(left_pts), len(right_pts), len(residual))
    left_pts = left_pts[:n]
    right_pts = right_pts[:n]
    residual = residual[:n]

    support = _residual_model_support_summary(left_pts, image_shape)
    matrix, labels = _y_residual_design_matrix(left_pts, right_pts, image_shape, terms)
    # Store the exact normalization used by the design matrix so the visual
    # apply basis can evaluate the same low-order field on a full-resolution
    # image grid.  The x²/y² columns are centred on the matched-point
    # distribution, not on a theoretical whole-image average.
    h_norm, w_norm = image_shape[:2]
    cx_norm = (float(w_norm) - 1.0) / 2.0
    cy_norm = (float(h_norm) - 1.0) / 2.0
    if n:
        x_norm_values = (left_pts[:, 0] - cx_norm) / max(1.0, float(w_norm))
        y_norm_values = (left_pts[:, 1] - cy_norm) / max(1.0, float(h_norm))
        disp_values = right_pts[:, 0] - left_pts[:, 0]
        normalization = {
            "x2_mean": float(np.mean(x_norm_values * x_norm_values)),
            "y2_mean": float(np.mean(y_norm_values * y_norm_values)),
            "disp_median_analysis_px": float(np.median(disp_values)),
            "analysis_width": int(w_norm),
            "analysis_height": int(h_norm),
        }
    else:
        normalization = {
            "x2_mean": 0.0,
            "y2_mean": 0.0,
            "disp_median_analysis_px": 0.0,
            "analysis_width": int(w_norm),
            "analysis_height": int(h_norm),
        }
    param_count = matrix.shape[1]
    eval_mask = _holdout_mask_for_residual_basis(left_pts, Y_RESIDUAL_HOLDOUT_STRIDE)
    train_mask = ~eval_mask
    if int(np.sum(train_mask)) < max(param_count + 4, param_count * Y_RESIDUAL_MIN_TRAIN_POINTS_PER_PARAMETER):
        train_mask[:] = True
        eval_mask[:] = False

    ready = (
        n >= Y_RESIDUAL_MIN_TOTAL_POINTS
        and param_count > 0
        and int(np.sum(train_mask)) >= max(param_count + 4, param_count * Y_RESIDUAL_MIN_TRAIN_POINTS_PER_PARAMETER)
        and support["reliable_zones"] >= Y_RESIDUAL_MIN_RELIABLE_ZONES
    )

    max_abs_model = min(
        float(Y_RESIDUAL_MAX_CORRECTION_ANALYSIS_PX),
        float(Y_RESIDUAL_MAX_CORRECTION_FRACTION) * float(max(1, min(image_shape[:2]))),
    )

    if not ready:
        beta = np.zeros((param_count,), dtype=np.float64)
        model = np.zeros((n,), dtype=np.float64)
    else:
        weights = _zone_capped_weights(left_pts, image_shape, ZONE_DIAGNOSTICS_GRID, Y_RESIDUAL_ZONE_SOFT_CAP_PER_ZONE)
        beta = _weighted_lstsq(matrix[train_mask], residual[train_mask], weights[train_mask])
        model = matrix @ beta
        model = np.clip(model, -max_abs_model, max_abs_model)

    corrected = residual - model
    eval_indices = np.where(eval_mask)[0]
    if len(eval_indices) == 0:
        eval_indices = np.arange(n, dtype=np.int64)
        eval_note = "no_holdout_available_eval_uses_all_points"
    else:
        eval_note = "spatial_holdout"

    def local_summary(values: np.ndarray) -> dict:
        signed_px = np.asarray(values, dtype=np.float64).reshape(-1) / max(1e-12, float(analysis_scale))
        if len(signed_px) == 0:
            return {"mean_signed": None, "mean_abs": None, "median_abs": None, "p90_abs": None, "p95_abs": None, "max_abs": None}
        abs_px = np.abs(signed_px)
        return {
            "mean_signed": float(np.mean(signed_px)),
            "mean_abs": float(np.mean(abs_px)),
            "median_abs": float(np.median(abs_px)),
            "p90_abs": float(np.percentile(abs_px, 90)),
            "p95_abs": float(np.percentile(abs_px, 95)),
            "max_abs": float(np.max(abs_px)),
        }

    coefficient_rows = []
    for label, value in zip(labels, beta.tolist()):
        coefficient_rows.append({
            "term": label,
            "coefficient_analysis_px": float(value),
            "coefficient_fullres_px_approx": float(value) / max(1e-12, float(analysis_scale)),
        })

    return {
        "name": name,
        "terms": labels,
        "ready": bool(ready),
        "support": support,
        "train_points": int(np.sum(train_mask)),
        "eval_points": int(len(eval_indices)),
        "eval_mode": eval_note,
        "max_abs_model_analysis_px": float(max_abs_model),
        "max_abs_model_fullres_px": float(max_abs_model) / max(1e-12, float(analysis_scale)),
        "coefficients": coefficient_rows,
        "normalization": normalization,
        "model_summary": local_summary(model),
        "vertical": local_summary(corrected),
        "vertical_holdout": local_summary(corrected[eval_indices]),
        "baseline_holdout": local_summary(residual[eval_indices]),
        "zone3x3": _vertical_residual_zone_stats(left_pts, corrected, image_shape, analysis_scale, ZONE_DIAGNOSTICS_GRID),
        "zone3x3_holdout": _vertical_residual_zone_stats(left_pts[eval_indices], corrected[eval_indices], image_shape, analysis_scale, ZONE_DIAGNOSTICS_GRID),
        "vs_affine": None,  # filled by the caller because it needs affine zone stats
        "vs_affine_holdout_mean_abs_delta": None,
    }

def _weighted_lstsq(a: np.ndarray, target: np.ndarray, weights: np.ndarray | None) -> np.ndarray:
    if weights is None:
        params, *_ = np.linalg.lstsq(a, target, rcond=None)
        return params
    w = np.asarray(weights, dtype=np.float64).reshape(-1)
    if len(w) != len(target) or not np.all(np.isfinite(w)) or float(np.sum(w)) <= 1e-12:
        params, *_ = np.linalg.lstsq(a, target, rcond=None)
        return params
    sw = np.sqrt(np.clip(w, 0.0, None))
    params, *_ = np.linalg.lstsq(a * sw[:, None], target * sw, rcond=None)
    return params

def _vertical_residual_zone_stats(
    anchor_points: np.ndarray,
    vertical_residual_signed_analysis: np.ndarray,
    image_shape: tuple[int, int],
    analysis_scale: float,
    grid: int = 3,
) -> dict:
    pts = np.asarray(anchor_points, dtype=np.float64).reshape(-1, 2)
    signed = np.asarray(vertical_residual_signed_analysis, dtype=np.float64).reshape(-1)
    n = min(len(pts), len(signed))
    pts = pts[:n]
    signed = signed[:n]
    if n == 0:
        labels = ZONE3X3_LABELS if grid == 3 else [str(i) for i in range(grid * grid)]
        return {
            "grid": int(grid),
            "labels": labels,
            "zones": [],
            "occupied_zones": 0,
            "mean_abs": None,
            "median_abs": None,
            "p90_abs": None,
            "p95_abs": None,
            "max_abs": None,
            "worst_zone_label": None,
            "worst_zone_mean_abs": None,
        }

    scale = max(1e-12, float(analysis_scale))
    signed_px = signed / scale
    abs_px = np.abs(signed_px)
    zones = _grid_zone_indices(pts, image_shape, grid)
    labels = ZONE3X3_LABELS if grid == 3 else [str(i) for i in range(grid * grid)]

    zone_rows = []
    occupied = 0
    worst_label = None
    worst_mean = None
    for idx in range(grid * grid):
        mask = zones == idx
        count = int(np.sum(mask))
        label = labels[idx] if idx < len(labels) else str(idx)
        if count == 0:
            zone_rows.append({
                "label": label,
                "count": 0,
                "mean_signed": None,
                "mean_abs": None,
                "median_abs": None,
                "p90_abs": None,
                "max_abs": None,
            })
            continue
        occupied += 1
        signed_zone = signed_px[mask]
        abs_zone = abs_px[mask]
        mean_abs = float(np.mean(abs_zone))
        if worst_mean is None or mean_abs > worst_mean:
            worst_mean = mean_abs
            worst_label = label
        zone_rows.append({
            "label": label,
            "count": count,
            "mean_signed": float(np.mean(signed_zone)),
            "mean_abs": mean_abs,
            "median_abs": float(np.median(abs_zone)),
            "p90_abs": float(np.percentile(abs_zone, 90)),
            "max_abs": float(np.max(abs_zone)),
        })

    def mean_for_indices(indices: list[int]) -> float | None:
        mask = np.isin(zones, indices)
        if int(np.sum(mask)) == 0:
            return None
        return float(np.mean(abs_px[mask]))

    return {
        "grid": int(grid),
        "labels": labels,
        "zones": zone_rows,
        "occupied_zones": int(occupied),
        "counts": [row["count"] for row in zone_rows],
        "mean_abs": float(np.mean(abs_px)),
        "median_abs": float(np.median(abs_px)),
        "p90_abs": float(np.percentile(abs_px, 90)),
        "p95_abs": float(np.percentile(abs_px, 95)),
        "max_abs": float(np.max(abs_px)),
        "worst_zone_label": worst_label,
        "worst_zone_mean_abs": worst_mean,
        "top_mean_abs": mean_for_indices([0, 1, 2]),
        "middle_mean_abs": mean_for_indices([3, 4, 5]),
        "bottom_mean_abs": mean_for_indices([6, 7, 8]),
        "left_mean_abs": mean_for_indices([0, 3, 6]),
        "center_col_mean_abs": mean_for_indices([1, 4, 7]),
        "right_mean_abs": mean_for_indices([2, 5, 8]),
        "corner_mean_abs": mean_for_indices([0, 2, 6, 8]),
        "edge_mean_abs": mean_for_indices([0, 1, 2, 3, 5, 6, 7, 8]),
        "center_zone_mean_abs": mean_for_indices([4]),
    }

def _zone_improvement_stats(before: dict, after: dict, epsilon_px: float = 0.01) -> dict:
    before_zones = {z.get("label"): z for z in before.get("zones", [])}
    after_zones = {z.get("label"): z for z in after.get("zones", [])}
    rows = []
    improved = 0
    worsened = 0
    unchanged = 0
    worst_worsening_label = None
    worst_worsening = None
    best_improvement_label = None
    best_improvement = None
    for label, b in before_zones.items():
        a = after_zones.get(label)
        if not a:
            continue
        b_mean = b.get("mean_abs")
        a_mean = a.get("mean_abs")
        if b_mean is None or a_mean is None:
            continue
        delta = float(a_mean) - float(b_mean)
        if delta < -epsilon_px:
            improved += 1
        elif delta > epsilon_px:
            worsened += 1
        else:
            unchanged += 1
        if worst_worsening is None or delta > worst_worsening:
            worst_worsening = delta
            worst_worsening_label = label
        if best_improvement is None or delta < best_improvement:
            best_improvement = delta
            best_improvement_label = label
        rows.append({"label": label, "delta_mean_abs": delta})
    return {
        "epsilon_px": float(epsilon_px),
        "zones_compared": len(rows),
        "improved_zones": int(improved),
        "worsened_zones": int(worsened),
        "unchanged_zones": int(unchanged),
        "worst_worsening_label": worst_worsening_label,
        "worst_worsening_delta": worst_worsening,
        "best_improvement_label": best_improvement_label,
        "best_improvement_delta": best_improvement,
        "zone_deltas": rows,
        "mean_abs_delta": None if before.get("mean_abs") is None or after.get("mean_abs") is None else float(after["mean_abs"] - before["mean_abs"]),
        "worst_zone_mean_abs_delta": None if before.get("worst_zone_mean_abs") is None or after.get("worst_zone_mean_abs") is None else float(after["worst_zone_mean_abs"] - before["worst_zone_mean_abs"]),
    }

def _lms_affine_from_vertical_residuals(
    right_points: np.ndarray,
    left_points: np.ndarray,
    image_shape: tuple[int, int],
) -> tuple[float, float, float, str]:
    """Fit the StereoFine affine parameters by vertical least squares.

    The fitted correction parameters are the same parameters later used by the
    symmetric image warp: vertical centre shift, relative rotation and scale.
    The linearized residual model is intentionally small and stereo-safe:

        right_y' - left_y' ~= (right_y - left_y)
                             + dy
                             + theta * x_mean_centered
                             + log(scale) * y_mean_centered

    We solve for dy/theta/log(scale) so that the squared vertical residual is
    minimized over the y-RANSAC-filtered inlier set.  If the linear fit becomes
    implausible, the analysis fails deliberately instead of falling back to a
    different correction model.
    """
    right_pts = np.asarray(right_points, dtype=np.float64).reshape(-1, 2)
    left_pts = np.asarray(left_points, dtype=np.float64).reshape(-1, 2)
    if len(right_pts) < 8 or len(left_pts) < 8:
        raise RuntimeError("Zu wenige Inlier für LMS-Affine-Schätzung.")

    h, w = image_shape[:2]
    cx = (float(w) - 1.0) / 2.0
    cy = (float(h) - 1.0) / 2.0

    dy_raw = right_pts[:, 1] - left_pts[:, 1]
    x_mean_centered = 0.5 * ((right_pts[:, 0] - cx) + (left_pts[:, 0] - cx))
    y_mean_centered = 0.5 * ((right_pts[:, 1] - cy) + (left_pts[:, 1] - cy))

    # Scale columns so the least-squares solve is well conditioned while the
    # recovered parameters remain in physical units afterwards.
    sx = max(1.0, float(w))
    sy = max(1.0, float(h))
    a = np.column_stack([
        np.ones(len(dy_raw), dtype=np.float64),
        x_mean_centered / sx,
        y_mean_centered / sy,
    ])
    target = -dy_raw.astype(np.float64)

    params_scaled = _weighted_lstsq(a, target, None)
    affine_fit_method = "vertical_lms"

    centre_shift_y = float(params_scaled[0])
    theta_rad = float(params_scaled[1] / sx)
    log_scale = float(params_scaled[2] / sy)

    rotation_deg = float(np.degrees(theta_rad))
    scale = float(np.exp(log_scale))

    # Plausibility guard. Normal stereo corrections are tiny; if the
    # vertical-only LMS fit becomes ill-conditioned, stop the automatic analysis
    # instead of silently switching to another correction model.
    plausible = (
        np.isfinite(centre_shift_y)
        and np.isfinite(rotation_deg)
        and np.isfinite(scale)
        and abs(centre_shift_y) <= 0.25 * max(1.0, float(h))
        and abs(rotation_deg) <= 5.0
        and 0.90 <= scale <= 1.10
    )
    if not plausible:
        raise RuntimeError("LMS-Schätzung ist geometrisch unplausibel; automatische Korrektur abgebrochen.")

    return scale, rotation_deg, centre_shift_y, affine_fit_method

def _affine_from_center_params(
    width: int,
    height: int,
    rotation_deg: float,
    scale: float,
    center_dx: float,
    center_dy: float,
) -> np.ndarray:
    """Build a simple image operation around the image centre.

    This is the same conceptual operation as in an image editor: rotate/scale
    around the centre and move the centre by dx/dy. It is deliberately not a
    fitted OpenCV model.
    """
    cx = (float(width) - 1.0) / 2.0
    cy = (float(height) - 1.0) / 2.0
    theta = np.radians(float(rotation_deg))
    c = np.cos(theta) * float(scale)
    si = np.sin(theta) * float(scale)
    linear = np.array([[c, -si], [si, c]], dtype=np.float64)
    centre = np.array([cx, cy], dtype=np.float64)
    target_centre = centre + np.array([center_dx, center_dy], dtype=np.float64)
    t = target_centre - linear @ centre
    return np.array([[linear[0, 0], linear[0, 1], t[0]], [linear[1, 0], linear[1, 1], t[1]]], dtype=np.float64)

def _correction_without_y_residual(correction: dict | None) -> dict | None:
    if not correction:
        return correction
    stripped = dict(correction)
    payload = dict(stripped.get("y_residual_apply") or {})
    if payload:
        payload["enabled"] = False
        stripped["y_residual_apply"] = payload
    return stripped

def _y_residual_field_from_payload(height: int, width: int, payload: dict | None) -> np.ndarray | None:
    """Evaluate a stored low-order y residual field on an image grid.

    The payload stores full-resolution pixel coefficients.  x/y are normalized
    image coordinates, matching the diagnostic fit.  `disp` terms are refused
    here because a dense disparity/depth map is not available and using such a
    term as a plain image warp would be stereoscopically unsafe.
    """
    if not payload or not bool(payload.get("enabled", False)):
        return None
    terms = list(payload.get("terms") or [])
    if not terms or "disp" in terms:
        return None
    coeff_rows = payload.get("coefficients") or []
    coeff_by_term = {}
    for row in coeff_rows:
        term = row.get("term")
        if term is not None:
            coeff_by_term[str(term)] = float(row.get("coefficient_fullres_px", 0.0))
    if not coeff_by_term:
        return None

    yy, xx = np.indices((height, width), dtype=np.float32)
    cx = (float(width) - 1.0) / 2.0
    cy = (float(height) - 1.0) / 2.0
    x = (xx - cx) / max(1.0, float(width))
    y = (yy - cy) / max(1.0, float(height))
    norm = payload.get("normalization") or {}
    x2_mean = float(norm.get("x2_mean", 0.0) or 0.0)
    y2_mean = float(norm.get("y2_mean", 0.0) or 0.0)

    field = np.zeros((height, width), dtype=np.float32)
    for term in terms:
        coeff = float(coeff_by_term.get(term, 0.0))
        if abs(coeff) <= 1e-12:
            continue
        if term == "constant":
            field += coeff
        elif term == "x":
            field += coeff * x
        elif term == "y":
            field += coeff * y
        elif term == "xy":
            field += coeff * x * y
        elif term == "x2":
            field += coeff * ((x * x) - x2_mean)
        elif term == "y2":
            field += coeff * ((y * y) - y2_mean)

    max_abs = float(payload.get("max_abs_correction_px", 0.0) or 0.0)
    if max_abs > 0:
        field = np.clip(field, -max_abs, max_abs)
    return field.astype(np.float32)

def _warp_pair_symmetric_simple(
    left: np.ndarray,
    right: np.ndarray,
    correction: dict | None,
) -> tuple[np.ndarray, np.ndarray]:
    """Apply the complete symmetric StereoFine geometry with one resample/eye.

    The former development pipeline rendered Affine first and then resampled
    again for Vergence/Trapezoid and Y-Polish. 1.0 composes the corresponding
    inverse coordinate maps analytically and calls ``cv2.remap`` exactly once
    per half-image. This preserves the established geometry while avoiding
    cumulative interpolation loss.
    """
    if not correction:
        return center_crop_to_common_size(left, right)[:2]

    try:
        import cv2
    except Exception:
        return center_crop_to_common_size(left, right)[:2]

    h = min(left.shape[0], right.shape[0])
    w = min(left.shape[1], right.shape[1])
    if h <= 2 or w <= 2:
        return center_crop_to_common_size(left, right)[:2]

    left_base = np.ascontiguousarray(left[:h, :w])
    right_base = np.ascontiguousarray(right[:h, :w])

    rotation = float(correction.get("rotation_deg", 0.0) or 0.0)
    scale = max(1e-6, float(correction.get("scale", 1.0) or 1.0))
    dy = float(correction.get("vertical_shift_px", 0.0) or 0.0)

    vergence_ready = bool(correction.get("vergence_ready", False))
    vergence_v = float(correction.get("vergence_v_px", 0.0) or 0.0) if vergence_ready else 0.0
    vergence_h = float(correction.get("vergence_h_px", 0.0) or 0.0) if vergence_ready else 0.0

    trapez_payload = correction.get("trapez_apply") or {}
    trapez_enabled = bool(trapez_payload.get("enabled", False))
    trapez_params = trapez_payload.get("params") or {}
    trapez_a = float(trapez_params.get("a_projective_x", 0.0) or 0.0) if trapez_enabled else 0.0
    trapez_b = float(trapez_params.get("b_projective_y", 0.0) or 0.0) if trapez_enabled else 0.0

    y_residual_field = _y_residual_field_from_payload(h, w, correction.get("y_residual_apply"))
    has_y_residual = y_residual_field is not None and bool(np.any(np.abs(y_residual_field) > 1e-12))

    # Preserve true identity pixel-for-pixel. Apart from being faster, this is
    # important for already-perfect pairs and for color-transfer negative tests.
    if (
        abs(rotation) <= 1e-12
        and abs(scale - 1.0) <= 1e-12
        and abs(dy) <= 1e-12
        and abs(vergence_v) <= 1e-12
        and abs(vergence_h) <= 1e-12
        and abs(trapez_a) <= 1e-12
        and abs(trapez_b) <= 1e-12
        and not has_y_residual
    ):
        return left_base, right_base

    yy, xx = np.indices((h, w), dtype=np.float32)
    cx = (float(w) - 1.0) / 2.0
    cy = (float(h) - 1.0) / 2.0

    half_scale = scale ** 0.5
    m_left = _affine_from_center_params(w, h, -rotation / 2.0, 1.0 / half_scale, 0.0, -dy / 2.0)
    m_right = _affine_from_center_params(w, h, rotation / 2.0, half_scale, 0.0, dy / 2.0)
    inv_left = cv2.invertAffineTransform(m_left).astype(np.float64)
    inv_right = cv2.invertAffineTransform(m_right).astype(np.float64)

    def composed_map(side: str) -> tuple[np.ndarray, np.ndarray]:
        # Start at the final destination grid and walk backwards through the
        # exact order of the old sequential image operations:
        # Y-Polish -> Trapezoid -> Vergence -> Affine -> master.
        qx = xx.astype(np.float64)
        qy = yy.astype(np.float64)

        if has_y_residual:
            half_y = 0.5 * y_residual_field.astype(np.float64)
            if side == "left":
                qy = qy - half_y
            else:
                qy = qy + half_y

        if abs(trapez_a) > 1e-12 or abs(trapez_b) > 1e-12:
            u = qx - cx
            v = qy - cy
            xn = u / max(1.0, float(w))
            yn = v / max(1.0, float(h))
            side_strength = -0.5 if side == "left" else +0.5
            projective_q = side_strength * (trapez_a * xn + trapez_b * yn)
            denom = 1.0 - projective_q
            denom = np.where(
                np.abs(denom) < 1e-6,
                np.where(denom < 0.0, -1e-6, 1e-6),
                denom,
            )
            qx = cx + u / denom
            qy = cy + v / denom

        if abs(vergence_v) > 1e-12 or abs(vergence_h) > 1e-12:
            x_norm = (qx - cx) / max(1.0, float(w))
            y_norm = (qy - cy) / max(1.0, float(h))
            half_v = 0.5 * vergence_v * x_norm
            half_h = 0.5 * vergence_h * y_norm
            if side == "left":
                qx = qx - half_h
                qy = qy - half_v
            else:
                qx = qx + half_h
                qy = qy + half_v

        inv = inv_left if side == "left" else inv_right
        src_x = inv[0, 0] * qx + inv[0, 1] * qy + inv[0, 2]
        src_y = inv[1, 0] * qx + inv[1, 1] * qy + inv[1, 2]
        return src_x.astype(np.float32), src_y.astype(np.float32)

    left_map_x, left_map_y = composed_map("left")
    right_map_x, right_map_y = composed_map("right")

    # A single high-quality interpolation per master image.
    left_warped = cv2.remap(
        left_base,
        left_map_x,
        left_map_y,
        interpolation=cv2.INTER_LANCZOS4,
        borderMode=cv2.BORDER_CONSTANT,
        borderValue=(0, 0, 0),
    )
    right_warped = cv2.remap(
        right_base,
        right_map_x,
        right_map_y,
        interpolation=cv2.INTER_LANCZOS4,
        borderMode=cv2.BORDER_CONSTANT,
        borderValue=(0, 0, 0),
    )

    # Determine the common fully valid area directly from the composed master
    # maps. This replaces the repeatedly resampled binary masks of the old path.
    left_valid = (
        np.isfinite(left_map_x)
        & np.isfinite(left_map_y)
        & (left_map_x >= -0.5)
        & (left_map_x < float(w) - 0.5)
        & (left_map_y >= -0.5)
        & (left_map_y < float(h) - 0.5)
    )
    right_valid = (
        np.isfinite(right_map_x)
        & np.isfinite(right_map_y)
        & (right_map_x >= -0.5)
        & (right_map_x < float(w) - 0.5)
        & (right_map_y >= -0.5)
        & (right_map_y < float(h) - 0.5)
    )
    crop_box = _largest_all_valid_rectangle(left_valid & right_valid)
    if crop_box is None:
        return center_crop_to_common_size(left_warped, right_warped)[:2]

    x0, y0, x1, y1 = crop_box
    return (
        np.ascontiguousarray(left_warped[y0:y1, x0:x1]),
        np.ascontiguousarray(right_warped[y0:y1, x0:x1]),
    )

def warp_pair_symmetric(
    left: np.ndarray,
    right: np.ndarray,
    correction: dict | None,
) -> tuple[np.ndarray, np.ndarray]:
    """Public rendering entry point for the validated StereoFine correction payload."""
    return _warp_pair_symmetric_simple(left, right, correction)


