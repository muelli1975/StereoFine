def _fit_vertical_ransac_filter(
    anchor_points: np.ndarray,
    right_points: np.ndarray,
    left_points: np.ndarray,
    image_shape: tuple[int, int],
    threshold_analysis_px: float = 3.0,
    max_iters: int = 3000,
) -> dict:
    """RANSAC candidate that scores only vertical residuals.

    It fits dy = right_y - left_y as a low-order plane over the image:
    dy ~= c + ax + by. Horizontal disparity is deliberately ignored during
    inlier scoring because it is scene depth, not vertical stereo error.
    """
    pts = np.asarray(anchor_points, dtype=np.float64).reshape(-1, 2)
    rp = np.asarray(right_points, dtype=np.float64).reshape(-1, 2)
    lp = np.asarray(left_points, dtype=np.float64).reshape(-1, 2)
    n = min(len(pts), len(rp), len(lp))
    pts = pts[:n]
    rp = rp[:n]
    lp = lp[:n]
    if n < 8:
        mask = np.zeros((n,), dtype=bool)
        residual = np.zeros((n,), dtype=np.float64)
        return {"ready": False, "mask": mask, "residual_y_analysis_px": residual, "coefficients": []}

    h, w = image_shape[:2]
    cx = (float(w) - 1.0) / 2.0
    cy = (float(h) - 1.0) / 2.0
    x_norm = (pts[:, 0] - cx) / max(1.0, float(w))
    y_norm = (pts[:, 1] - cy) / max(1.0, float(h))
    X = np.column_stack([np.ones(n, dtype=np.float64), x_norm, y_norm])
    dy = rp[:, 1] - lp[:, 1]

    rng = np.random.default_rng(1337)
    best_mask = None
    best_score = (-1, float("inf"))
    indices = np.arange(n)
    iterations = int(min(max_iters, max(300, n * 3)))
    for _ in range(iterations):
        sample = rng.choice(indices, size=3, replace=False)
        try:
            beta = np.linalg.solve(X[sample], dy[sample])
        except np.linalg.LinAlgError:
            continue
        residual = dy - X @ beta
        abs_res = np.abs(residual)
        m = abs_res <= float(threshold_analysis_px)
        count = int(np.sum(m))
        if count <= 0:
            continue
        med = float(np.median(abs_res[m]))
        score = (count, -med)
        if best_mask is None or score > best_score:
            best_mask = m
            best_score = score

    if best_mask is None or int(np.sum(best_mask)) < 8:
        # Robust fallback: ordinary least squares over all matches, mainly so
        # diagnostics still contain meaningful residuals.
        beta, *_ = np.linalg.lstsq(X, dy, rcond=None)
        residual = dy - X @ beta
        mask = np.abs(residual) <= float(threshold_analysis_px)
    else:
        beta, *_ = np.linalg.lstsq(X[best_mask], dy[best_mask], rcond=None)
        residual = dy - X @ beta
        mask = np.abs(residual) <= float(threshold_analysis_px)

    return {
        "ready": bool(int(np.sum(mask)) >= 8),
        "mask": mask.astype(bool),
        "residual_y_analysis_px": residual.astype(np.float64),
        "coefficients": [
            {"term": "constant", "coefficient_analysis_px": float(beta[0])},
            {"term": "x_norm", "coefficient_analysis_px": float(beta[1])},
            {"term": "y_norm", "coefficient_analysis_px": float(beta[2])},
        ],
        "threshold_analysis_px": float(threshold_analysis_px),
        "note": "Diagnostic y-only RANSAC candidate: scores vertical residuals only and ignores horizontal disparity.",
    }

