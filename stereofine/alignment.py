def _quadrant_counts(points: np.ndarray, image_shape: tuple[int, int]) -> list[int]:
    pts = np.asarray(points, dtype=np.float64).reshape(-1, 2)
    h, w = image_shape[:2]
    cx = w / 2.0
    cy = h / 2.0
    return [
        int(np.sum((pts[:, 0] < cx) & (pts[:, 1] < cy))),
        int(np.sum((pts[:, 0] >= cx) & (pts[:, 1] < cy))),
        int(np.sum((pts[:, 0] < cx) & (pts[:, 1] >= cy))),
        int(np.sum((pts[:, 0] >= cx) & (pts[:, 1] >= cy))),
    ]

def _fit_vergence_from_affine_residuals(
    left_points_after_affine: np.ndarray,
    right_points_after_affine: np.ndarray,
    image_shape: tuple[int, int],
) -> tuple[float, float]:
    """Estimate Vergence V/H with a least-squares residual fit.

    StereoFine keeps this model deliberately limited:
    - Affine (height/rotation/scale) is estimated from y-RANSAC-filtered inliers.
    - Vergence V/H is only measured from the affine residual field.

    In this zone basis, the slope fit can optionally use the same 3x3 zone
    balancing as affine LMS. That tests whether a more evenly distributed point
    pattern supports the first-order V/H terms better than raw point density.
    """
    left_pts = np.asarray(left_points_after_affine, dtype=np.float64).reshape(-1, 2)
    right_pts = np.asarray(right_points_after_affine, dtype=np.float64).reshape(-1, 2)
    if len(left_pts) < 4 or len(right_pts) < 4:
        return 0.0, 0.0

    h, w = image_shape[:2]
    cx = (float(w) - 1.0) / 2.0
    cy = (float(h) - 1.0) / 2.0

    residual_x = right_pts[:, 0] - left_pts[:, 0]
    residual_y = right_pts[:, 1] - left_pts[:, 1]

    rx = residual_x - float(np.median(residual_x))
    ry = residual_y - float(np.median(residual_y))

    x_norm = (left_pts[:, 0] - cx) / max(1.0, float(w))
    y_norm = (left_pts[:, 1] - cy) / max(1.0, float(h))

    def lms_slope(axis: np.ndarray, values: np.ndarray) -> float:
        mask = np.isfinite(axis) & np.isfinite(values) & (np.abs(axis) > 1e-6)
        if int(mask.sum()) < 4:
            return 0.0
        a = axis[mask].astype(np.float64)
        v = values[mask].astype(np.float64)
        denom = float(np.dot(a, a))
        if denom <= 1e-12:
            return 0.0
        return float(np.dot(a, v) / denom)

    vergence_v_px = lms_slope(x_norm, ry)
    vergence_h_px = lms_slope(y_norm, rx)
    return vergence_v_px, vergence_h_px

def _pipeline_mean_points(left_points: np.ndarray, right_points: np.ndarray) -> np.ndarray:
    left_pts = np.asarray(left_points, dtype=np.float64).reshape(-1, 2)
    right_pts = np.asarray(right_points, dtype=np.float64).reshape(-1, 2)
    n = min(len(left_pts), len(right_pts))
    if n == 0:
        return np.zeros((0, 2), dtype=np.float64)
    return 0.5 * (left_pts[:n] + right_pts[:n])

def _pipeline_vertical_residual_signed(left_points: np.ndarray, right_points: np.ndarray) -> np.ndarray:
    left_pts = np.asarray(left_points, dtype=np.float64).reshape(-1, 2)
    right_pts = np.asarray(right_points, dtype=np.float64).reshape(-1, 2)
    n = min(len(left_pts), len(right_pts))
    if n == 0:
        return np.zeros((0,), dtype=np.float64)
    return right_pts[:n, 1] - left_pts[:n, 1]

def _pipeline_holdout_mask(points: np.ndarray, stride: int = TRAPEZ_HOLDOUT_STRIDE) -> tuple[np.ndarray, np.ndarray]:
    pts = np.asarray(points, dtype=np.float64).reshape(-1, 2)
    n = len(pts)
    if n == 0:
        return np.zeros((0,), dtype=np.int64), np.zeros((0,), dtype=np.int64)
    stride = max(3, int(stride))
    order = np.lexsort((pts[:, 0], pts[:, 1]))
    holdout_mask = np.zeros((n,), dtype=bool)
    holdout_mask[order[::stride]] = True
    if int(np.sum(holdout_mask)) >= n - 4:
        holdout_mask[:] = False
        holdout_mask[::stride] = True
    train_mask = ~holdout_mask
    if int(np.sum(train_mask)) < 8:
        train_mask[:] = True
        holdout_mask[:] = False
    return np.where(train_mask)[0], np.where(holdout_mask)[0]

def _pipeline_design_quality(features: np.ndarray, weights: np.ndarray | None = None) -> dict:
    """Numerical support check for the 2-parameter trapez fit.

    Pipeline v4 deliberately removes the hard four-quadrant gate.  Instead we
    check whether the actual design matrix is solvable: enough rows, finite
    values, rank 2 and a sane condition number.  This is a numerical stability
    test, not a manually guessed image-area rule.
    """
    a = np.asarray(features, dtype=np.float64)
    if a.ndim != 2 or a.shape[1] == 0:
        return {
            "rows": 0,
            "cols": 0,
            "rank": 0,
            "condition": None,
            "supported": False,
            "reason": "empty_design_matrix",
        }

    mask = np.all(np.isfinite(a), axis=1)
    a = a[mask]
    if weights is not None:
        w = np.asarray(weights, dtype=np.float64).reshape(-1)
        w = w[mask] if len(w) == len(mask) else np.ones((len(a),), dtype=np.float64)
        if len(w) == len(a) and np.all(np.isfinite(w)) and float(np.sum(w)) > 1e-12:
            a = a * np.sqrt(np.clip(w, 0.0, None))[:, None]

    rows, cols = a.shape
    if rows < max(cols + 4, TRAPEZ_MIN_TRAIN_POINTS):
        return {
            "rows": int(rows),
            "cols": int(cols),
            "rank": 0,
            "condition": None,
            "supported": False,
            "reason": "too_few_training_points",
        }

    try:
        singular_values = np.linalg.svd(a, compute_uv=False)
    except Exception:
        return {
            "rows": int(rows),
            "cols": int(cols),
            "rank": 0,
            "condition": None,
            "supported": False,
            "reason": "svd_failed",
        }

    if len(singular_values) == 0 or not np.all(np.isfinite(singular_values)):
        return {
            "rows": int(rows),
            "cols": int(cols),
            "rank": 0,
            "condition": None,
            "supported": False,
            "reason": "nonfinite_singular_values",
        }

    s0 = float(singular_values[0])
    smin = float(singular_values[-1])
    tol = max(a.shape) * np.finfo(np.float64).eps * max(s0, 1.0)
    rank = int(np.sum(singular_values > tol))
    condition = None if smin <= tol else float(s0 / smin)
    supported = bool(rank >= cols and condition is not None and condition <= TRAPEZ_MAX_DESIGN_CONDITION)
    reason = "ok"
    if rank < cols:
        reason = "rank_deficient_design"
    elif condition is None:
        reason = "singular_design"
    elif condition > TRAPEZ_MAX_DESIGN_CONDITION:
        reason = "ill_conditioned_design"

    return {
        "rows": int(rows),
        "cols": int(cols),
        "rank": int(rank),
        "condition": condition,
        "singular_values": [float(v) for v in singular_values.tolist()],
        "supported": bool(supported),
        "reason": reason,
        "max_condition": float(TRAPEZ_MAX_DESIGN_CONDITION),
    }

def _pipeline_ridge_lstsq(
    features: np.ndarray,
    target: np.ndarray,
    ridge: float = 1e-8,
    weights: np.ndarray | None = None,
) -> np.ndarray:
    a = np.asarray(features, dtype=np.float64)
    y = np.asarray(target, dtype=np.float64)
    mask = np.all(np.isfinite(a), axis=1) & np.isfinite(y)
    a = a[mask]
    y = y[mask]
    w = None
    if weights is not None:
        weights_arr = np.asarray(weights, dtype=np.float64).reshape(-1)
        if len(weights_arr) == len(mask):
            w = weights_arr[mask]

    if len(y) == 0 or a.shape[0] < a.shape[1]:
        raise RuntimeError("Zu wenige gültige Punkte für Trapez-Least-Squares-Fit.")

    if w is not None and len(w) == len(y) and np.all(np.isfinite(w)) and float(np.sum(w)) > 1e-12:
        sw = np.sqrt(np.clip(w, 0.0, None))
        a = a * sw[:, None]
        y = y * sw

    ata = a.T @ a
    aty = a.T @ y
    reg = np.eye(a.shape[1], dtype=np.float64) * float(ridge)
    return np.linalg.solve(ata + reg, aty)

def fit_pipeline_trapez_projective_model(
    left_points_after_base: np.ndarray,
    right_points_after_base: np.ndarray,
    image_shape: tuple[int, int],
    train_idx: np.ndarray,
) -> dict:
    left_train = np.asarray(left_points_after_base, dtype=np.float64).reshape(-1, 2)[train_idx]
    right_train = np.asarray(right_points_after_base, dtype=np.float64).reshape(-1, 2)[train_idx]
    mean_train = _pipeline_mean_points(left_train, right_train)
    residual = _pipeline_vertical_residual_signed(left_train, right_train)
    h, w = image_shape[:2]
    cx = (float(w) - 1.0) / 2.0
    cy = (float(h) - 1.0) / 2.0
    u = mean_train[:, 0] - cx
    v = mean_train[:, 1] - cy
    x_norm = u / max(1.0, float(w))
    y_norm = v / max(1.0, float(h))
    # Begrenzter projektiver Trapez-/Kippterm: x/y werden gemeinsam über einen
    # zentrischen Nenner verändert, aber Fit-Ziel bleibt ausschließlich der
    # vertikale Restfehler. Horizontale Disparität wird nicht minimiert.
    features = np.column_stack([v * x_norm, v * y_norm])
    weights = _zone_capped_weights(
        mean_train,
        image_shape,
        ZONE_DIAGNOSTICS_GRID,
        TRAPEZ_ZONE_SOFT_CAP_PER_ZONE,
    )
    design_quality = _pipeline_design_quality(features, weights=weights)
    if not bool(design_quality.get("supported", False)):
        raise RuntimeError(f"Trapez-Fit nicht stabil genug: {design_quality.get('reason')}")
    coeff = _pipeline_ridge_lstsq(features, residual, ridge=1e-6, weights=weights)
    return {
        "a_projective_x": float(coeff[0]),
        "b_projective_y": float(coeff[1]),
        "fit_method": "centered_projective_2param_vertical_lms_zone_capped",
        "target": "vertical_residual_only",
        "horizontal_disparity_target": "not_minimized",
        "design_quality": design_quality,
        "zone_soft_cap_per_zone": int(TRAPEZ_ZONE_SOFT_CAP_PER_ZONE),
    }

def apply_pipeline_trapez_projective_to_points(
    left_points: np.ndarray,
    right_points: np.ndarray,
    image_shape: tuple[int, int],
    params: dict,
) -> tuple[np.ndarray, np.ndarray]:
    a = float(params.get("a_projective_x", 0.0) or 0.0)
    b = float(params.get("b_projective_y", 0.0) or 0.0)

    def transform(points: np.ndarray, side_strength: float) -> np.ndarray:
        pts = np.asarray(points, dtype=np.float64).reshape(-1, 2)
        h, w = image_shape[:2]
        cx = (float(w) - 1.0) / 2.0
        cy = (float(h) - 1.0) / 2.0
        u = pts[:, 0] - cx
        v = pts[:, 1] - cy
        x_norm = u / max(1.0, float(w))
        y_norm = v / max(1.0, float(h))
        denom = 1.0 + side_strength * (a * x_norm + b * y_norm)
        denom[np.abs(denom) < 1e-9] = 1e-9
        out = np.empty_like(pts, dtype=np.float64)
        out[:, 0] = cx + u / denom
        out[:, 1] = cy + v / denom
        return out

    return transform(left_points, -0.5), transform(right_points, +0.5)

def pipeline_trapez_plausibility(image_shape: tuple[int, int], params: dict) -> dict:
    a = float(params.get("a_projective_x", 0.0) or 0.0)
    b = float(params.get("b_projective_y", 0.0) or 0.0)
    h, w = image_shape[:2]
    corners = np.array(
        [[0.0, 0.0], [float(w - 1), 0.0], [float(w - 1), float(h - 1)], [0.0, float(h - 1)]],
        dtype=np.float64,
    )
    left_c, right_c = apply_pipeline_trapez_projective_to_points(corners, corners, image_shape, params)
    left_shift = np.linalg.norm(left_c - corners, axis=1)
    right_shift = np.linalg.norm(right_c - corners, axis=1)
    max_corner_shift_px = float(max(np.max(left_shift), np.max(right_shift)))
    max_corner_shift_permille = max_corner_shift_px / max(1.0, float(w)) * 1000.0

    def edge_lengths(pts: np.ndarray) -> np.ndarray:
        return np.array([
            np.linalg.norm(pts[1] - pts[0]),
            np.linalg.norm(pts[2] - pts[1]),
            np.linalg.norm(pts[2] - pts[3]),
            np.linalg.norm(pts[3] - pts[0]),
        ], dtype=np.float64)

    base_lengths = edge_lengths(corners)
    left_lengths = edge_lengths(left_c)
    right_lengths = edge_lengths(right_c)
    stretch_left = np.abs(left_lengths / np.maximum(base_lengths, 1e-12) - 1.0) * 100.0
    stretch_right = np.abs(right_lengths / np.maximum(base_lengths, 1e-12) - 1.0) * 100.0
    max_edge_stretch_percent = float(max(np.max(stretch_left), np.max(stretch_right)))

    sample = np.vstack([corners, np.array([[(float(w - 1)) / 2.0, (float(h - 1)) / 2.0]], dtype=np.float64)])
    cx = (float(w) - 1.0) / 2.0
    cy = (float(h) - 1.0) / 2.0
    x_norm = (sample[:, 0] - cx) / max(1.0, float(w))
    y_norm = (sample[:, 1] - cy) / max(1.0, float(h))
    denom_left = 1.0 - 0.5 * (a * x_norm + b * y_norm)
    denom_right = 1.0 + 0.5 * (a * x_norm + b * y_norm)
    min_denom = float(min(np.min(denom_left), np.min(denom_right)))
    relative_y_delta_corners = right_c[:, 1] - left_c[:, 1]
    max_relative_y_correction_px_analysis = float(np.max(np.abs(relative_y_delta_corners)))

    warning_checks = {
        "param_abs_warning_ok": abs(a) <= TRAPEZ_WARNING_MAX_PARAM_ABS and abs(b) <= TRAPEZ_WARNING_MAX_PARAM_ABS,
        "denominator_warning_ok": min_denom >= TRAPEZ_WARNING_MIN_DENOMINATOR,
        "corner_shift_warning_ok": max_corner_shift_permille <= TRAPEZ_WARNING_MAX_CORNER_SHIFT_PERMILLE,
        "edge_stretch_warning_ok": max_edge_stretch_percent <= TRAPEZ_WARNING_MAX_EDGE_STRETCH_PERCENT,
    }
    hard_checks = {
        "finite_ok": bool(np.isfinite(a) and np.isfinite(b) and np.isfinite(min_denom)),
        "param_abs_hard_ok": abs(a) <= TRAPEZ_HARD_MAX_PARAM_ABS and abs(b) <= TRAPEZ_HARD_MAX_PARAM_ABS,
        "denominator_hard_ok": min_denom >= TRAPEZ_HARD_MIN_DENOMINATOR,
    }
    return {
        "plausible": bool(all(hard_checks.values())),
        "warning": not bool(all(warning_checks.values())),
        "checks": warning_checks,
        "hard_checks": hard_checks,
        "a_projective_x": a,
        "b_projective_y": b,
        "max_corner_shift_px_analysis": max_corner_shift_px,
        "max_corner_shift_permille_width": max_corner_shift_permille,
        "max_edge_stretch_percent": max_edge_stretch_percent,
        "max_relative_y_correction_px_analysis": max_relative_y_correction_px_analysis,
        "min_half_denominator": min_denom,
        "note": "Warnwerte sind Diagnose; harte Checks nur Notbremse gegen numerisch absurde Projektivterme.",
    }

