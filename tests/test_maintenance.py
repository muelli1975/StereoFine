def legacy_rectangle(valid: np.ndarray) -> tuple[int, int, int, int] | None:
    """Return the largest axis-aligned rectangle fully inside a valid mask.

    The mask is generated by warping an all-white source mask with the same
    affine transform as the right image. Therefore every True pixel represents
    real source image content after the warp.
    
    Coordinates are x0, y0, x1, y1 with x1/y1 exclusive.
    """
    if valid.ndim != 2 or not valid.any():
        return None

    h, w = valid.shape
    heights = [0] * w
    best_area = 0
    best_rect = None

    for y in range(h):
        row = valid[y]
        for x in range(w):
            heights[x] = heights[x] + 1 if row[x] else 0

        stack = []
        for x in range(w + 1):
            current_height = heights[x] if x < w else 0

            while stack and heights[stack[-1]] > current_height:
                height = heights[stack.pop()]
                x0 = stack[-1] + 1 if stack else 0
                x1 = x
                width = x1 - x0
                area = height * width

                if area > best_area:
                    best_area = area
                    y1 = y + 1
                    y0 = y1 - height
                    best_rect = (x0, y0, x1, y1)

            stack.append(x)

    if best_rect is None:
        return None

    x0, y0, x1, y1 = best_rect

    # Deterministic safety margin against interpolation fringes at the exact
    # border of the warped image. This is not a crop heuristic; it is a fixed
    # one-pixel guard band around a mathematically valid rectangle.
    margin = 2
    if x1 - x0 > margin * 2 and y1 - y0 > margin * 2:
        x0 += margin
        y0 += margin
        x1 -= margin
        y1 -= margin

    if x1 - x0 <= 2 or y1 - y0 <= 2:
        return None

    return x0, y0, x1, y1


def legacy_color_curve(image, sources, targets, strength):
    peak = 255.0 if image.dtype == np.uint8 else 65535.0 if image.dtype == np.uint16 else 1.0
    src = np.asarray(image, dtype=np.float32)
    if peak != 1.0:
        src = src / np.float32(peak)
    src = np.clip(src, 0.0, 1.0)
    out = np.empty_like(src, dtype=np.float32)
    for channel in range(3):
        xp = np.asarray(sources[channel], dtype=np.float32)
        fp = np.asarray(targets[channel], dtype=np.float32)
        unique, inverse = np.unique(xp, return_inverse=True)
        if len(unique) != len(xp):
            sums = np.zeros(len(unique), dtype=np.float64)
            counts = np.zeros(len(unique), dtype=np.int32)
            for index, group in enumerate(inverse):
                sums[group] += float(fp[index])
                counts[group] += 1
            xp, fp = unique, (sums / np.maximum(1, counts)).astype(np.float32)
        mapped = np.interp(src[..., channel], xp, fp).astype(np.float32)
        if strength < 1.0:
            mapped = src[..., channel] + np.float32(strength) * (mapped - src[..., channel])
        out[..., channel] = mapped
    out = np.clip(out, 0.0, 1.0)
    if image.dtype in (np.uint8, np.uint16):
        return np.rint(out * np.float32(peak)).astype(image.dtype)
    return out.astype(image.dtype, copy=False)


def loaded_pair(left, right):
    h, w = left.shape[:2]
    return LoadedStereoPair(left, right, Path('L.png'), Path('R.png'), 'pair', w, h, w, h, w, h)


class MaintenanceTests(unittest.TestCase):
    def test_preview_and_export_use_same_source_aspect(self):
        rng = np.random.default_rng(145)
        left = rng.integers(0, 256, (240, 360, 3), dtype=np.uint8)
        loaded = loaded_pair(left, np.roll(left, -9, axis=1))
        for aspect in ASPECT_RATIOS:
            for orientation in ('0', '90_cw'):
                for zoom, pan in ((0, 0), (3, 500), (6, -500)):
                    with self.subTest(aspect=aspect, orientation=orientation, zoom=zoom):
                        state = PairState()
                        state.input_transform.left_orientation = orientation
                        state.input_transform.right_orientation = orientation
                        state.alignment.valid = True
                        state.alignment.correction = {'rotation_deg': 2.0, 'scale': 1.003, 'vertical_shift_px': 3.0}
                        state.manual.delta_x_px = 18
                        state.manual.delta_y_px = -3
                        state.framing.aspect = aspect
                        state.framing.crop_zoom_index = zoom
                        state.framing.pan_x_permille = pan
                        state.framing.pan_y_permille = -pan
                        preview = render_preview_pair(loaded, state, max_width=2000, max_height=2000)
                        final_l, final_r, _ = render_final_pair(loaded, state)
                        np.testing.assert_array_equal(preview.left, final_l)
                        np.testing.assert_array_equal(preview.right, final_r)
                        if aspect == 'original':
                            target = 1.5 if orientation == '0' else 1 / 1.5
                            self.assertLessEqual(abs(final_l.shape[1] - target * final_l.shape[0]), 1.0)

    def test_original_aspect_agrees_with_disparity_framing(self):
        left = np.full((240, 360, 3), 127, np.uint8)
        state = PairState()
        state.framing.aspect = 'original'
        state.alignment.valid = True
        state.alignment.correction = {'rotation_deg': 2.0, 'scale': 1.0, 'vertical_shift_px': 4.0}
        dleft, dright = render_pair_for_disparity_analysis_from_arrays(
            left, left, state.alignment.correction, output_aspect='original', input_aspect_ratio=1.5
        )
        final_l, final_r, _ = render_final_pair(loaded_pair(left, left), state)
        np.testing.assert_array_equal(dleft, final_l)
        np.testing.assert_array_equal(dright, final_r)

    def test_reference_analysis_retains_validated_geometry_and_deviation(self):
        from stereofine.processing import ProcessingOptions
        root = Path(__file__).resolve().parents[1] / 'assets'
        source = source_from_stereo_file(root / 'stereofine.jpg', root)
        item = process_source(source, ProcessingOptions(save_sidecar=False))
        self.assertEqual(item.state.alignment.model, 'Affine')
        self.assertAlmostEqual(item.state.alignment.vertical_error_mean_px, .10198, delta=.005)
        self.assertAlmostEqual(item.state.disparity.total_permille, 19.833, delta=.05)
        self.assertFalse((root / '_stereofine').exists())

    def test_color_tables_exhaust_integer_values_with_duplicate_knots(self):
        sources = ((0., .1, .1, .4, .7, 1.), (0., .2, .4, .4, .9, 1.), (0., .1, .5, .7, .9, 1.))
        targets = ((0., .15, .3, .5, .8, 1.),) * 3
        transfer = SymmetricColorTransfer(COLOR_METHOD, (10., 30., 50., 80.), sources, sources[::-1], targets)
        for dtype, side in ((np.uint8, 16), (np.uint16, 256)):
            ramp = np.arange(side * side, dtype=dtype).reshape(side, side)
            left = np.stack((ramp, np.flipud(ramp), np.fliplr(ramp)), axis=2)[:, ::-1]
            right = left[::-1]
            for strength in (0., .2, .35, .7, 1.):
                with self.subTest(dtype=dtype, strength=strength):
                    actual_l, actual_r = apply_symmetric_color_transfer(left, right, transfer, strength=strength)
                    np.testing.assert_array_equal(actual_l, legacy_color_curve(left, sources, targets, strength))
                    np.testing.assert_array_equal(actual_r, legacy_color_curve(right, sources[::-1], targets, strength))

    def test_color_float_and_small_integer_fallbacks_are_unchanged(self):
        curves = ((0., .2, .5, .8, 1.),) * 3
        targets = ((0., .15, .55, .9, 1.),) * 3
        transfer = SymmetricColorTransfer(COLOR_METHOD, (20., 50., 80.), curves, curves, targets)
        rng = np.random.default_rng(38)
        for dtype in (np.float32, np.float64, np.uint8, np.uint16):
            a = rng.random((7, 9, 3))
            if np.issubdtype(dtype, np.integer):
                a *= np.iinfo(dtype).max
            a = a.astype(dtype)
            actual, _ = apply_symmetric_color_transfer(a, a, transfer, strength=.35)
            np.testing.assert_array_equal(actual, legacy_color_curve(a, curves, targets, .35))

    def test_rectangle_matches_release_for_every_four_by_four_mask(self):
        shifts = np.arange(16)
        for bits in range(1 << 16):
            mask = ((bits >> shifts) & 1).astype(bool).reshape(4, 4)
            self.assertEqual(_largest_all_valid_rectangle(mask), legacy_rectangle(mask), bits)

    def test_rectangle_matches_release_for_scaled_ties_and_random_masks(self):
        shifts = np.arange(9)
        for bits in range(1 << 9):
            mask = np.repeat(np.repeat(((bits >> shifts) & 1).reshape(3, 3), 3, axis=0), 4, axis=1).astype(bool)
            self.assertEqual(_largest_all_valid_rectangle(mask), legacy_rectangle(mask), bits)
        rng = np.random.default_rng(415)
        for _ in range(2000):
            h, w = rng.integers(3, 60, size=2)
            mask = rng.random((h, w)) < rng.uniform(.1, .99)
            self.assertEqual(_largest_all_valid_rectangle(mask), legacy_rectangle(mask))
        for mask in (np.zeros((0, 0), bool), np.ones(4, bool), np.ones((8, 12), np.uint8) * 255):
            self.assertEqual(_largest_all_valid_rectangle(mask), legacy_rectangle(mask))

    def test_composed_warp_keeps_exact_pixels_and_crop(self):
        rng = np.random.default_rng(137)
        corrections = [
            None,
            {'rotation_deg': 0.0, 'scale': 1.0, 'vertical_shift_px': 0.0},
            {'rotation_deg': 1.7, 'scale': 1.004, 'vertical_shift_px': -3.2},
            {'rotation_deg': -.7, 'scale': .998, 'vertical_shift_px': 2.5,
             'trapez_apply': {'enabled': True, 'params': {'a_projective_x': .014, 'b_projective_y': -.012}}},
            {'rotation_deg': .7, 'scale': 1.002, 'vertical_shift_px': -2.,
             'y_residual_apply': {'enabled': True, 'coefficients': [{'term': 'xy', 'coefficient_fullres_px': 2.}],
                                  'max_abs_correction_px': 3., 'normalization': {}}},
        ]
        for dtype, peak in ((np.uint8, 256), (np.uint16, 65536)):
            left = rng.integers(0, peak, (140, 210, 3), dtype=dtype)
            right = np.roll(left, -7, axis=1)
            for correction in corrections:
                with patch('stereofine.alignment._largest_all_valid_rectangle', legacy_rectangle):
                    expected_l, expected_r = warp_pair_symmetric(left, right, correction)
                actual_l, actual_r = warp_pair_symmetric(left, right, correction)
                np.testing.assert_array_equal(actual_l, expected_l)
                np.testing.assert_array_equal(actual_r, expected_r)

