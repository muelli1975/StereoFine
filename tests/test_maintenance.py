    def test_batch_checks_all_output_names_before_processing(self):
        with tempfile.TemporaryDirectory() as td:
            root = Path(td)
            sources = [source_from_stereo_file(root / folder / 'Motiv.jpg', root / folder) for folder in ('a', 'b')]
            validate_source_names(sources, check_outputs=False)
            with patch('stereofine.batch.process_source') as process:
                with self.assertRaises(InputError):
                    run_batch(sources, BatchRunOptions(output_folder=root / 'output'))
                process.assert_not_called()
            self.assertFalse((root / 'output').exists())

    def test_other_source_cannot_overwrite_legacy_sidecar(self):
        with tempfile.TemporaryDirectory() as td:
            root = Path(td)
            source = {'kind': 'full_sbs', 'left': {'path': 'Motiv.jpg'}, 'right': {'path': 'Motiv.jpg'}}
            path = root / '_stereofine' / 'Motiv.sfin'
            original = SidecarDocument(source=source, favorite=True, manual={'delta_x_px': 4, 'delta_y_px': 2})
            save_sidecar(path, original)
            previous = path.read_bytes()
            other = {'kind': 'full_sbs', 'left': {'path': 'Motiv.png'}, 'right': {'path': 'Motiv.png'}}
            with self.assertRaises(ValueError):
                save_sidecar(path, SidecarDocument(source=other))
            self.assertEqual(path.read_bytes(), previous)
            changed_source = {**source, 'left': {**source['left'], 'mtime_ns': 123}}
            save_sidecar(path, replace(original, source=changed_source))
            self.assertIn('"favorite": true', path.read_text())

    def test_normal_names_remain_unchanged_and_collision_message_is_translated(self):
        source = source_from_stereo_file(Path('/photos/Motiv.jpg'), Path('/photos'))
        self.assertEqual(source.base_name, 'Motiv')
        self.assertEqual(source.sidecar_path, Path('/photos/_stereofine/Motiv.sfin'))
        text = 'Gleicher Dateistamm – bitte Quelldateien eindeutig umbenennen: Motiv.jpg, Motiv.png'
        translated = Translator('en').message(text)
        self.assertTrue(translated.startswith('Duplicate filename stem'))
        self.assertIn('Motiv.jpg, Motiv.png', translated)

    def test_gui_reports_collision_without_replacing_current_collection(self):
        from types import SimpleNamespace
        from stereofine import gui
        with tempfile.TemporaryDirectory() as td:
            root = Path(td)
            for name in ('Motiv.jpg', 'Motiv.png', 'Motiv_l.jpg', 'Motiv_l.png', 'Motiv_r.jpg'):
                Image.new('RGB', (120, 40)).save(root / name)
            fake = SimpleNamespace(
                _t=lambda key: key,
                _stereo_filetypes=lambda: [],
                _dialog_initial_dir=lambda: str(root),
                _set_source_collection=unittest.mock.Mock(),
                tr=Translator('en'),
            )
            for handler in ('choose_single_stereo', 'choose_batch_stereo', 'choose_batch_pair'):
                with self.subTest(handler=handler), \
                     patch.object(gui.filedialog, 'askopenfilename', return_value=str(root / 'Motiv.jpg')), \
                     patch.object(gui.filedialog, 'askdirectory', return_value=str(root)), \
                     patch.object(gui.messagebox, 'showerror') as error:
                    getattr(gui.StereoFineApp, handler)(fake)
                    error.assert_called_once()
                    self.assertIn('unique names', error.call_args.args[1])
            fake._set_source_collection.assert_not_called()


